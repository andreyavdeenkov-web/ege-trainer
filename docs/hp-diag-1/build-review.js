const quote = (s) => s.split('\n').map((l) => '> ' + l).join('\n');

function questionText(t) {
  const q = Array.isArray(t.question) ? t.question : [t.question];
  const lines = [];
  for (const part of q) {
    if (typeof part === 'string') lines.push(part);
    else if (part.list) part.list.forEach((x) => lines.push('• ' + x));
    else if (part.table) lines.push(part.table.map((r) => r.join(' — ')).join('; '));
    else if (part.terms) lines.push(part.terms.join(', ') + '.');
  }
  return lines.join('\n\n');
}

function correctAnswer(t) {
  if (t.type === 'multiple-select') return t.options.map((o, i) => (o.correct ? i + 1 : null)).filter(Boolean).join(', ');
  return t.keyDisplay || '—';
}

