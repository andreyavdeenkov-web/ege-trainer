/**
 * Рабочий банк практикума «Норма права»: общие строки для заданий на классификацию нормы.
 * Подключается к странице olympiad-work.html перед файлами заданий.
 *
 * Формат задания на классификацию (утверждён преподавателем): одно нормативное предписание →
 * несколько вопросов по основаниям классификации → одна проверка → объяснение. Без доказательств,
 * без подсчёта предписаний и дополнительных частей. Спорные основания в автоматическую оценку
 * не включаются.
 *
 * Отраслевая принадлежность — всегда из общего широкого набора отраслей (BRANCHES), а не из 3–4
 * вариантов. Для каждой неверной отрасли объяснение строится из предмета этой отрасли; для
 * правдоподобных ошибок задание даёт своё объяснение (specific).
 */
(function (root) {
  'use strict';

  var OLY = root.OLY || (root.OLY = {});

  var BRANCHES = [
    { name: 'Конституционное право', gen: 'конституционного права', subject: 'основы конституционного строя, права и свободы человека и гражданина, организацию государственной власти и местного самоуправления' },
    { name: 'Административное право', gen: 'административного права', subject: 'отношения в сфере государственного управления и административную ответственность' },
    { name: 'Гражданское право', gen: 'гражданского права', subject: 'имущественные и связанные с ними личные неимущественные отношения участников гражданского оборота' },
    { name: 'Семейное право', gen: 'семейного права', subject: 'брачно-семейные отношения: брак, отношения родителей и детей, алиментные обязательства' },
    { name: 'Трудовое право', gen: 'трудового права', subject: 'трудовые отношения работников и работодателей и непосредственно связанные с ними отношения' },
    { name: 'Уголовное право', gen: 'уголовного права', subject: 'преступность и наказуемость деяний' },
    { name: 'Гражданское процессуальное право', gen: 'гражданского процессуального права', subject: 'порядок рассмотрения и разрешения гражданских дел судами' },
    { name: 'Уголовно-процессуальное право', gen: 'уголовно-процессуального права', subject: 'порядок досудебного и судебного производства по уголовным делам' },
    { name: 'Финансовое право', gen: 'финансового права', subject: 'образование, распределение и использование публичных денежных фондов, в том числе налоги и сборы' },
    { name: 'Земельное право', gen: 'земельного права', subject: 'использование и охрану земель, права на земельные участки' },
    { name: 'Экологическое право', gen: 'экологического права', subject: 'охрану окружающей среды и природопользование' }
  ];

  /**
   * Строка «Отраслевая принадлежность».
   * opts: { id?, label?, key: 'Семейное право', regulates: 'обязанность родителей содержать детей',
   *         specific?: { 'Гражданское право': '…' | { short, full } }, explanation }
   */
  function branchRow(opts) {
    var keyIndex = -1;
    BRANCHES.forEach(function (b, i) { if (b.name === opts.key) keyIndex = i; });
    if (keyIndex === -1) throw new Error('Неизвестная отрасль: ' + opts.key);
    var key = BRANCHES[keyIndex];
    var wrong = {};
    BRANCHES.forEach(function (b, i) {
      if (i === keyIndex) return;
      wrong[i] = (opts.specific && opts.specific[b.name]) ||
        (b.name + ' регулирует ' + b.subject + '. Анализируемая норма регулирует ' + opts.regulates + ' — это предмет ' + key.gen + '.');
    });
    return {
      id: opts.id || 'branch', short: 'Отрасль', label: opts.label || '1. Отраслевая принадлежность',
      options: BRANCHES.map(function (b) { return b.name; }),
      key: [keyIndex], wrong: wrong, explanation: opts.explanation
    };
  }

  OLY.nrmClassify = { BRANCHES: BRANCHES, branchRow: branchRow };
})(typeof window !== 'undefined' ? window : globalThis);
