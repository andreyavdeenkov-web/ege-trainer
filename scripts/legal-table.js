#!/usr/bin/env node
'use strict';
/**
 * Сверочная таблица нормативных положений обязательной части практикума
 * «Норма права: понятие, признаки, классификация и структура» (тема LAW-NRM).
 *
 *   node scripts/legal-table.js — обновить docs/drafts/pr-law-nrm-verification-table.md и .csv
 *
 * Цитаты берутся из рабочего банка дословно, статусы — из журнала work/law-nrm/verification.json.
 * Скрипт ничего не подтверждает: статус меняется только в журнале после сверки с официальным источником.
 */
const fs = require('node:fs');
const path = require('node:path');
const { loadBank } = require('../tests/helpers/olymp.js');
const { collect, JOURNAL } = require('./legal-checklist.js');

const root = path.join(__dirname, '..');
const MD = path.join(root, 'docs/drafts/pr-law-nrm-verification-table.md');
const CSV = path.join(root, 'docs/drafts/pr-law-nrm-verification-table.csv');

const PORTAL = 'pravo.gov.ru — ИПС «Законодательство России», действующая редакция; изменяющие акты — publication.pravo.gov.ru';

/* Приоритет, что проверить и риск для ключа — по экспертизе от 12.10.2026. */
const META = {
  'ТК РФ | ст. 12, ч. 5': [1, 'Есть ли основание «вступление в силу закона… устанавливающего более высокий уровень гарантий работникам»; дословная формулировка основания', 'Высокий: если основания нет или оно иное, меняется ключ П5 («положение прекратило действие») и фрагмент-доказательство e11'],
  'ТК РФ | ст. 8, ч. 1': [1, 'Исключение для работодателей — физических лиц, не являющихся ИП; слова «в пределах своей компетенции»', 'Высокий: на «компетенции» держится ключ П2 («вне компетенции работодателя») и доказательство e3 в А4'],
  'ТК РФ | ст. 12, ч. 4': [1, 'Оба предложения дословно; границы фрагментов e7, e8, e9a, e9', 'Средний: иное деление текста — переразметка фрагментов и ключей доказательств П3, П4; суть ключей вряд ли изменится'],
  'Федеральный закон «О защите населения и территорий от чрезвычайных ситуаций природного и техногенного характера» | ст. 11, п. 1, пп. «у»': [1, 'Какой подпункт («у» или «ф») содержит слова «могут предусматривать дополнительные обязательные… правила поведения»; редакция после Федерального закона от 01.04.2020 № 98-ФЗ', 'Средний: ошибка реквизита — исправить ссылку; иная формулировка — фрагмент z2. Ключ А2 устойчив'],
  'ГК РФ | ст. 210': [1, 'Оговорка «если иное не предусмотрено законом или договором»', 'Высокий: на оговорке держится ключ «Диспозитивная»'],
  'УК РФ | ст. 125': [1, 'Действующая редакция; слова «был обязан иметь о нем заботу», «сам поставил его в опасное для жизни или здоровья состояние»', 'Средний: на этих словах держатся шаги 3 и 4 рассуждения'],
  'ТК РФ | ст. 76, ч. 1, абз. 1–2': [1, 'Дословно: «отстранить от работы (не допускать к работе)… появившегося… опьянения»', 'Средний: границы фрагментов разметки; ключ устойчив'],
  'Федеральный закон «Об образовании в Российской Федерации» | ст. 43, ч. 4': [1, 'Перечень актов в гипотезе и перечень мер; ограничения в частях 5–6 (упомянуты в объяснении)', 'Средний: границы фрагментов; текст объяснения'],
  'ТК РФ | ст. 419, ч. 1': [1, 'Дословно, включая обе отсылки к порядку', 'Средний: границы фрагментов; ключ устойчив'],
  'ТК РФ | ст. 122, ч. 2, первое предложение': [1, 'Первое предложение; содержание второго (исключение по соглашению сторон, упомянуто в объяснении)', 'Средний: фрагменты; текст объяснения об исключении'],
  'КоАП РФ | ст. 20.6.1, ч. 1': [2, 'Формулировка; размер штрафа для граждан (от 1 до 30 тыс. руб.)', 'Низкий: текст фрагментов k1, k2; ключ А4 устойчив'],
  'ТК РФ | ст. 108, чч. 1–2': [2, '«Время предоставления перерыва и его конкретная продолжительность устанавливаются правилами внутреннего трудового распорядка или по соглашению…»', 'Низкий: фрагмент e13; ключ П6 устойчив'],
  'ГПК РФ | ст. 39, ч. 1 (полномочия истца)': [2, 'Перечень правомочий истца', 'Низкий: только текст; ключи устойчивы'],
  'ТК РФ | ст. 21, ч. 2': [2, 'Обязанность «соблюдать правила внутреннего трудового распорядка», «соблюдать трудовую дисциплину»', 'Низкий: фрагмент e5'],
  'Конституция РФ | ст. 15, ч. 3': [2, 'Дословно, с учётом поправок 2020 г.', 'Низкий: фрагмент c2'],
  'ТК РФ | ст. 60': [3, 'Дословно', 'Минимальный: только текст объяснения к П3']
};

function main() {
  const OLY = loadBank('olympiad-work.html');
  const shown = OLY.sortByOrder(OLY.tasks.filter((t) => t.topic === 'LAW-NRM' && t.olympiad === 'PR'));
  const num = (id) => shown.findIndex((t) => t.id === id) + 1;
  const journal = JSON.parse(fs.readFileSync(JOURNAL, 'utf8')).entries;
  const rows = [];
  for (const [k, it] of collect()) {
    const ids = it.tasks.filter((id) => /^PR-LAW-NRM-/.test(id));
    if (!ids.length) continue;
    if (!META[k]) throw new Error('Нет приоритета и риска для положения: ' + k);
    const j = journal[k] || {};
    const [prio, check, risk] = META[k];
    rows.push({ prio, act: it.act, ref: it.ref, tasks: ids.map((id) => num(id) + ' (' + id + ')').join(', '),
      quote: it.text, check, risk, source: PORTAL, status: j.status || 'pending', edition: j.edition || '', checked: j.checked || '', comment: j.comment || '' });
  }
  const RISK = ['Высокий', 'Средний', 'Низкий', 'Минимальный'];
  const rank = (r) => RISK.findIndex((x) => r.risk.startsWith(x));
  rows.sort((a, b) => a.prio - b.prio || rank(a) - rank(b));
  const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const md = [
    '# Сверочная таблица: нормативные положения обязательной части',
    '',
    'Практикум «Норма права: понятие, признаки, классификация и структура», тема `LAW-NRM`, 11 заданий. Сгенерировано `node scripts/legal-table.js` из рабочего банка и журнала `work/law-nrm/verification.json`; цитаты совпадают с текстом заданий дословно. Таблица для работы в редакторе — `pr-law-nrm-verification-table.csv`.',
    '',
    '**Статус.** `pending` — не сверено; `confirmed` — совпадает с официальным текстом; `differs` — расходится. Статус меняется только в журнале и только по официальному источнику; цитаты по памяти не исправляются. Номер задания — по порядку показа (в скобках — постоянный идентификатор).',
    '',
    '**Приоритет.** 1 — ключ зависит от дословного текста или реквизита; 2 — цитата служит доказательством, ключ устойчив; 3 — справочная цитата.',
    '',
    '| № | Приор. | Акт | Структурная единица | Задание | Используемая цитата | Что проверить | Риск для ключа | Источник | Статус |',
    '|---|---|---|---|---|---|---|---|---|---|'
  ];
  rows.forEach((r, i) => md.push('| ' + [i + 1, r.prio, r.act, r.ref, r.tasks, r.quote, r.check, r.risk, 'pravo.gov.ru', r.status].map(cell).join(' | ') + ' |'));
  md.push('', 'Указ губернатора N-ской области в задании 2 (PR-LAW-NRM-001) — учебный документ (`fictional: true`), сверке не подлежит.', '');
  fs.writeFileSync(MD, md.join('\n'));
  const q = (s) => '"' + String(s).replace(/"/g, '""') + '"';
  const head = ['№', 'Приоритет', 'Акт', 'Структурная единица', 'Задание', 'Используемая цитата', 'Что проверить', 'Риск для ключа', 'Источник', 'Статус', 'Редакция', 'Дата сверки', 'Комментарий / расхождение'];
  const csv = [head.map(q).join(';')].concat(rows.map((r, i) => [i + 1, r.prio, r.act, r.ref, r.tasks, r.quote, r.check, r.risk, r.source, r.status, r.edition, r.checked, r.comment].map(q).join(';')));
  fs.writeFileSync(CSV, '﻿' + csv.join('\r\n') + '\r\n');
  console.log('Положений обязательной части: ' + rows.length + '; таблица обновлена');
}

if (require.main === module) main();
